import { env } from './config/env';
import { createApp } from './app';
import { applyOverduePolicy } from './services/billing';
import { processOutbox } from './services/messaging';
import { autoGenerateDue } from './services/fees';
import { closeExpiredAttempts } from './routes/onlineExams';
import { autoGenerateMonthly } from './services/monthlyReports';
import { autoDigests } from './services/lms';

const app = createApp();
app.listen(env.PORT, () => console.log(`API listening on http://localhost:${env.PORT}`));

// Hourly: move schools with overdue subscription invoices to read-only / suspended.
setInterval(() => {
  applyOverduePolicy().catch((e) => console.error('overdue job failed', e));
  autoGenerateDue().catch((e) => console.error('fee auto-generate failed', e));
  // Early in each month: draft last month's progress reports for the principal to review and send.
  autoGenerateMonthly().catch((e) => console.error('monthly reports failed', e));
}, 60 * 60 * 1000).unref();

// Every minute: submit online exam attempts whose time is up.
setInterval(() => {
  closeExpiredAttempts().catch((e) => console.error('closing attempts failed', e));
}, 60 * 1000).unref();

// Every 5 minutes: send each section's daily diary to parents once the school's diary time has passed.
setInterval(() => {
  autoDigests().catch((e) => console.error('diary digest failed', e));
}, 5 * 60 * 1000).unref();

// Every few seconds: send queued WhatsApp messages.
let sending = false;
setInterval(async () => {
  if (sending) return;
  sending = true;
  try {
    while ((await processOutbox()) > 0);
  } catch (e) {
    console.error('outbox failed', e);
  } finally {
    sending = false;
  }
}, 4000).unref();
