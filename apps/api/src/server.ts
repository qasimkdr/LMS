import { env } from './config/env';
import { createApp } from './app';
import { applyOverduePolicy } from './services/billing';
import { processOutbox } from './services/messaging';
import { autoGenerateDue } from './services/fees';

const app = createApp();
app.listen(env.PORT, () => console.log(`API listening on http://localhost:${env.PORT}`));

// Hourly: move schools with overdue subscription invoices to read-only / suspended.
setInterval(() => {
  applyOverduePolicy().catch((e) => console.error('overdue job failed', e));
  autoGenerateDue().catch((e) => console.error('fee auto-generate failed', e));
}, 60 * 60 * 1000).unref();

// Every few seconds: send queued WhatsApp messages.
let sending = false;
setInterval(async () => {
  if (sending) return;
  sending = true;
  try {
    while ((await processOutbox()) > 0);
  } catch (e) {
    console.error('outbox failed', e);
  } finally {
    sending = false;
  }
}, 4000).unref();
