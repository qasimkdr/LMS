const num = (v: unknown) => Number(v);

/** Class 5 with tuition 3000 (discountable), computer 500 (not), annual 6000 in April; two siblings + one other student. */
async function feeSchool(principal: Client) {
  await principal.post('/api/setup/classes', { name: 'Class 5', sections: ['A'] });
  const cls = (await principal.get('/api/setup/structure')).body.classes[0];
  const add = async (name: string, guardians: unknown[] | null, familyId?: string, extra: Record<string, unknown> = {}) =>
    (await principal.post('/api/students', { student: { fullName: name, gender: 'MALE', classId: cls.id, sectionId: cls.sections[0].id, dob: '2015-01-01', admissionDate: '2026-01-01', ...extra }, ...(familyId ? { familyId } : { guardians }) })).body;
  const ali = await add('Ali Raza', [{ relation: 'FATHER', fullName: 'Raza Ahmed', phone: '03001234567' }]);
  const aliRow = await prisma.student.findUniqueOrThrow({ where: { id: ali.studentId } });
  const hira = await add('Hira Raza', null, aliRow.familyId, { discountType: 'Sibling', discountPercent: 10 });
  const sara = await add('Sara Khan', [{ relation: 'FATHER', fullName: 'Imran Khan', phone: '03005555555' }]);
  const saraRow = await prisma.student.findUniqueOrThrow({ where: { id: sara.studentId } });

  await principal.post('/api/fees/heads', { name: 'Tuition fee', frequency: 'MONTHLY', discountable: true, sortOrder: 1 });
  await principal.post('/api/fees/heads', { name: 'Computer fee', frequency: 'MONTHLY', discountable: false, sortOrder: 2 });
  await principal.post('/api/fees/heads', { name: 'Annual charges', frequency: 'SELECTED_MONTHS', months: [4], discountable: false, sortOrder: 3 });
  const setup = (await principal.get('/api/fees/setup')).body;
  const head = (n: string) => setup.heads.find((h: { name: string }) => h.name === n).id;
  await principal.put('/api/fees/structure', {
    rows: [
      { classId: cls.id, headId: head('Tuition fee'), amount: 3000 },
      { classId: cls.id, headId: head('Computer fee'), amount: 500 },
      { classId: cls.id, headId: head('Annual charges'), amount: 6000 },
    ],
  });
  await principal.put('/api/fees/settings', { dueDay: 10, lateFeeType: 'FIXED', lateFeeAmount: 200, autoGenerate: false, receiptPrefix: 'R' });
  return { cls, ali, hira, sara, familyId: aliRow.familyId, saraFamily: saraRow.familyId, head };
}

describe('fee calculations', () => {
  it('monthly lines include due heads and discount only discountable ones', () => {
    const heads = [
      { id: 't', name: 'Tuition', frequency: 'MONTHLY', months: null, discountable: true, amount: 3000 },
      { id: 'c', name: 'Computer', frequency: 'MONTHLY', months: null, discountable: false, amount: 500 },
      { id: 'a', name: 'Annual', frequency: 'SELECTED_MONTHS', months: [4], discountable: false, amount: 6000 },
    ];
    const march = monthlyLines(heads, 3, { percent: 10, amount: 100, label: 'Sibling' });
    expect(march.map((l) => l.amount)).toEqual([3000, 500, -400]);
    expect(monthlyLines(heads, 4, { percent: 0, amount: 0, label: null }).reduce((a, l) => a + l.amount, 0)).toBe(9500);
  });
  it('late fee rules', () => {
    const base = { lateFeeType: 'FIXED', lateFeeAmount: 200, lateFeeMax: 0 } as never;
    const due = new Date('2026-03-10T00:00:00Z');
    expect(lateFeeFor(base, due, '2026-03-10')).toBe(0);
    expect(lateFeeFor(base, due, '2026-03-11')).toBe(200);
    const perDay = { lateFeeType: 'PER_DAY', lateFeeAmount: 20, lateFeeMax: 300 } as never;
    expect(lateFeeFor(perDay, due, '2026-03-15')).toBe(100);
    expect(lateFeeFor(perDay, due, '2026-04-30')).toBe(300);
  });
});

describe('vouchers', () => {
  it('generates monthly vouchers once, with selected-month heads and student discounts', async () => {
    const { principal } = await setupSchool();
    const { hira, ali } = await feeSchool(principal);
    const g = await principal.post('/api/fees/generate', { period: '2026-04' });
    expect(g.body).toMatchObject({ created: 3, skipped: 0 });
    expect((await principal.post('/api/fees/generate', { period: '2026-04' })).body).toMatchObject({ created: 0, skipped: 3 });
    const aliInv = await prisma.feeInvoice.findFirstOrThrow({ where: { studentId: ali.studentId } });
    const hiraInv = await prisma.feeInvoice.findFirstOrThrow({ where: { studentId: hira.studentId } });
    expect(num(aliInv.total)).toBe(9500); // tuition + computer + annual (April)
    expect(num(hiraInv.total)).toBe(9200); // 10% sibling discount on tuition only
    expect(aliInv.dueDate.toISOString().slice(0, 10)).toBe('2026-04-10');

    // Students admitted after a month are not charged for it.
    await prisma.student.update({ where: { id: ali.studentId }, data: { admissionDate: new Date('2026-06-15') } });
    expect((await principal.post('/api/fees/generate', { period: '2026-05' })).body.created).toBe(2);
  });

  it('one-off charges and voucher printing data with arrears', async () => {
    const { principal } = await setupSchool();
    const { ali, familyId, cls } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' });
    await principal.post('/api/fees/generate', { period: '2026-04' });
    const c = await principal.post('/api/fees/charges', { studentIds: [ali.studentId], title: 'Study trip', lines: [{ description: 'Trip to museum', amount: 1500 }], dueDate: '2026-04-20' });
    expect(c.body.created).toBe(1);
    const p = (await principal.get(`/api/fees/vouchers/print?period=2026-04&classId=${cls.id}`)).body;
    const aliV = p.vouchers.find((v: { students: { id: string }[] }) => v.students[0].id === ali.studentId);
    expect(aliV.currentTotal).toBe(9500);
    expect(aliV.arrears).toBe(3500 + 1500); // March + trip
    const fam = (await principal.get(`/api/fees/vouchers/print?period=2026-04&familyId=${familyId}&family=true`)).body;
    expect(fam.vouchers).toHaveLength(1);
    expect(fam.vouchers[0].students).toHaveLength(2);
  });
});

describe('collection', () => {
  it('pays oldest vouchers first across siblings, keeps extra as credit, and uses it next month', async () => {
    const { principal } = await setupSchool();
    const { familyId } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' }); // Ali 3500, Hira 3200
    const dues = (await principal.get(`/api/fees/families/${familyId}/dues`)).body;
    expect(dues.due).toBe(6700);

    const r = await principal.post('/api/fees/payments', { familyId, amount: 8000, method: 'CASH', chargeLateFee: false });
    expect(r.status).toBe(201);
    expect(r.body.receiptNo).toBe('R-000001');
    expect(r.body.credit).toBe(1300);
    const inv = await prisma.feeInvoice.findMany({ where: { familyId } });
    expect(inv.every((i) => i.status === 'PAID')).toBe(true);

    await principal.post('/api/fees/generate', { period: '2026-05' }); // 3500 + 3200, credit 1300 applied
    const may = await prisma.feeInvoice.findMany({ where: { familyId, period: '2026-05' }, orderBy: { invoiceNo: 'asc' } });
    expect(may.reduce((a, i) => a + num(i.paidAmount), 0)).toBe(1300);
    const after = (await principal.get(`/api/fees/families/${familyId}/dues`)).body;
    expect(after.due).toBe(5400);
    expect(after.credit).toBe(0);
  });

  it('partial payment, late fee, and only the principal may waive it', async () => {
    const { principal, schoolId } = await setupSchool();
    const { saraFamily } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' }); // due 10 Mar, long past
    await createUser({ role: 'STAFF', username: 'clerk', schoolId, permissions: ['fees.collect'] });
    const clerk = await login('clerk');
    const d = (await clerk.get(`/api/fees/families/${saraFamily}/dues`)).body;
    expect(d.lateFee).toBe(200);
    expect((await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 1000, method: 'CASH', chargeLateFee: false })).status).toBe(403);
    const r = await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 1000, method: 'CASH' });
    expect(r.body.lateFeeAdded).toBe(200);
    const inv = await prisma.feeInvoice.findFirstOrThrow({ where: { familyId: saraFamily } });
    expect(num(inv.total)).toBe(3700);
    expect(inv.status).toBe('PARTIAL');
    // Late fee is added only once.
    const r2 = await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 2700, method: 'CASH' });
    expect(r2.body.lateFeeAdded).toBe(0);
    expect((await prisma.feeInvoice.findFirstOrThrow({ where: { familyId: saraFamily } })).status).toBe('PAID');
    // Staff cannot back-date.
    expect((await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 10, method: 'CASH', receivedAt: '2026-01-01' })).status).toBe(403);
  });

  it('sends the receipt on WhatsApp and in the app', async () => {
    const { principal } = await setupSchool();
    const { familyId } = await feeSchool(principal);
    await principal.put('/api/messaging/settings', { whatsappEnabled: true, phoneNumberId: '1234567890', accessToken: 'EAAG-test-token-1234567890' });
    await principal.post('/api/fees/generate', { period: '2026-03' });
    const r = await principal.post('/api/fees/payments', { familyId, amount: 3500, method: 'CASH', chargeLateFee: false });
    expect(r.body.whatsappQueued).toBe(1);
    await processOutbox();
    const m = await prisma.message.findFirstOrThrow({ where: { type: 'RECEIPT' } });
    expect(m.status).toBe('SENT');
    expect(m.body).toMatch(/received PKR 3,500 for Ali Raza/);
    expect(m.body).toMatch(/Remaining balance: PKR 3,200/);
    expect(await prisma.notification.count({ where: { type: 'RECEIPT' } })).toBe(1);
  });
});

describe('hand-over and cancellations', () => {
  it('staff hand over collected money; principal approves or rejects', async () => {
    const { principal, schoolId } = await setupSchool();
    const { familyId, saraFamily } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' });
    await createUser({ role: 'STAFF', username: 'clerk', schoolId, permissions: ['fees.collect'] });
    const clerk = await login('clerk');
    await clerk.post('/api/fees/payments', { familyId, amount: 3000, method: 'CASH' });
    await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 2000, method: 'BANK', reference: 'TT123' });
    const mine = (await clerk.get('/api/fees/handover/mine')).body;
    expect(mine.inHand.total).toBe(5000);
    expect(mine.inHand.byMethod).toEqual({ CASH: 3000, BANK: 2000 });

    const h = await clerk.post('/api/fees/handover', { declaredAmount: 4900, note: 'Short 100' });
    expect(h.body.difference).toBe(-100);
    expect((await clerk.get('/api/fees/handover/mine')).body.inHand.total).toBe(0);
    const list = (await principal.get('/api/fees/handovers?status=PENDING')).body;
    expect(list.handovers[0]).toMatchObject({ expectedAmount: 5000, declaredAmount: 4900, staff: 'clerk' });
    expect(await prisma.notification.count({ where: { type: 'HANDOVER' } })).toBe(1);

    expect((await principal.post(`/api/fees/handovers/${h.body.handoverId}/review`, { approve: false })).status).toBe(400); // needs a reason
    await principal.post(`/api/fees/handovers/${h.body.handoverId}/review`, { approve: false, note: 'Count again' });
    expect((await clerk.get('/api/fees/handover/mine')).body.inHand.total).toBe(5000);
    const h2 = await clerk.post('/api/fees/handover', { declaredAmount: 5000 });
    await principal.post(`/api/fees/handovers/${h2.body.handoverId}/review`, { approve: true });
    expect((await prisma.feeHandover.findUniqueOrThrow({ where: { id: h2.body.handoverId } })).status).toBe('APPROVED');
    expect((await clerk.post('/api/fees/handover', { declaredAmount: 0 })).status).toBe(400);
  });

  it('staff request cancellation; principal decides; cancelling restores the voucher balance', async () => {
    const { principal, schoolId } = await setupSchool();
    const { saraFamily } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' });
    await createUser({ role: 'STAFF', username: 'clerk', schoolId, permissions: ['fees.collect'] });
    const clerk = await login('clerk');
    const r = await clerk.post('/api/fees/payments', { familyId: saraFamily, amount: 3700, method: 'CASH' });
    expect((await clerk.post(`/api/fees/payments/${r.body.paymentId}/cancel`, { reason: 'Wrong family' })).body.status).toBe('CANCEL_REQUESTED');
    expect((await clerk.post('/api/fees/handover', { declaredAmount: 3700 })).status).toBe(400); // waiting for decision
    await principal.post(`/api/fees/payments/${r.body.paymentId}/cancel-decision`, { approve: true });
    const inv = await prisma.feeInvoice.findFirstOrThrow({ where: { familyId: saraFamily } });
    expect(inv.status).toBe('UNPAID');
    expect(num(inv.paidAmount)).toBe(0);
    expect((await prisma.feePayment.findUniqueOrThrow({ where: { id: r.body.paymentId } })).status).toBe('CANCELLED');
  });
});

