describe('online payment', () => {
  it('parent pays with the test gateway; receipt is created once', async () => {
    const { principal } = await setupSchool();
    const { ali } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' });
    expect((await principal.put('/api/pay/settings', { provider: 'TEST', enabled: true })).status).toBe(200);
    const parentLogin = ali.logins.find((l: { role: string }) => l.role === 'PARENT');
    await prisma.user.update({ where: { username: parentLogin.username }, data: { mustChangePassword: false } });
    const parent = await login(parentLogin.username, parentLogin.tempPassword);
    const my = (await parent.get('/api/fees/my')).body;
    expect(my.onlinePayment).toBe(true);
    expect(my.payable).toBe(6700 + 400); // two vouchers + late fee on each

    expect((await parent.post('/api/pay/start', { amount: 100 })).status).toBe(400); // partial not allowed
    const start = await parent.post('/api/pay/start', {});
    expect(start.body.method).toBe('GET');
    const ref = start.body.ref;
    await parent.post(`/api/pay/test/${ref}/complete`, { outcome: 'success' });
    await parent.post(`/api/pay/test/${ref}/complete`, { outcome: 'success' });
    expect(await prisma.feePayment.count({ where: { source: 'ONLINE' } })).toBe(1);
    const status = (await parent.get(`/api/pay/status/${ref}`)).body;
    expect(status.status).toBe('SUCCESS');
    expect(status.receipt.receiptNo).toMatch(/^R-/);
    expect((await parent.get('/api/fees/my')).body.due).toBe(0);
    // Online payments do not appear in anyone's cash in hand.
    expect((await principal.get('/api/fees/handover/mine')).body.inHand.total).toBe(0);
  });

  it('JazzCash: signs the checkout and trusts only correctly signed callbacks', async () => {
    const { principal, schoolId } = await setupSchool();
    const { ali } = await feeSchool(principal);
    await principal.post('/api/fees/generate', { period: '2026-03' });
    const salt = 'test-integrity-salt';
    await prisma.paymentGatewaySettings.create({ data: { schoolId, provider: 'JAZZCASH', enabled: true, merchantId: 'MC123', passwordEnc: encrypt('pw'), integritySaltEnc: encrypt(salt), sandbox: true, allowPartial: true } });
    const parentLogin = ali.logins.find((l: { role: string }) => l.role === 'PARENT');
    await prisma.user.update({ where: { username: parentLogin.username }, data: { mustChangePassword: false } });
    const parent = await login(parentLogin.username, parentLogin.tempPassword);
    const start = await parent.post('/api/pay/start', { amount: 1000 });
    expect(start.body.action).toMatch(/sandbox\.jazzcash\.com\.pk/);
    const f = start.body.fields as Record<string, string>;
    expect(f.pp_Amount).toBe('100000');
    expect(f.pp_SecureHash).toBe(jazzcashHash(f, salt));

    const callback = (fields: Record<string, string>) => request(app).post(`/api/pay/return/jazzcash/${schoolId}`).type('form').send(fields);
    const resp: Record<string, string> = { pp_TxnRefNo: f.pp_TxnRefNo, pp_Amount: '100000', pp_ResponseCode: '000', pp_ResponseMessage: 'Success', pp_MerchantID: 'MC123' };
    const tampered = await callback({ ...resp, pp_SecureHash: 'ABC' });
    expect(tampered.headers.location).toMatch(/payment=failed/);
    expect(await prisma.feePayment.count()).toBe(0);

    const ok = await callback({ ...resp, pp_SecureHash: jazzcashHash(resp, salt) });
    expect(ok.status).toBe(303);
    expect(ok.headers.location).toMatch(/payment=success/);
    const pay = await prisma.feePayment.findFirstOrThrow();
    expect(num(pay.amount)).toBe(1000);
    expect(jazzcashResult({ ...resp, pp_SecureHash: jazzcashHash(resp, salt) }, salt)).toMatchObject({ valid: true, success: true, amount: 1000 });
  });
});

